// Embeds each prisma/migrations/<name>/migration.sql into src/db/migrations.generated.ts for the runtime migrator.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import path from "node:path";

const dir = path.resolve(__dirname, "../prisma/migrations");
const names = readdirSync(dir).filter((n) => statSync(path.join(dir, n)).isDirectory()).sort();
const migrations = names.map((name) => ({ name, sql: readFileSync(path.join(dir, name, "migration.sql"), "utf8") }));
const out = `// AUTO-GENERATED by scripts/embed-migrations.ts — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(path.resolve(__dirname, "../src/db/migrations.generated.ts"), out);
console.log(`Embedded ${migrations.length} migration(s): ${names.join(", ")}`);
